"""Exporters for the LOD model. All lengths are metres."""
from __future__ import annotations

import datetime as _dt
import math
from xml.sax.saxutils import escape

import numpy as np

from .lod import triangulate


def _faces(model, layers):
    return [f for f in model["faces"] if f["layer"] in layers]


def _edges(model, layers):
    return [e for e in model["edges"] if any(l in layers for l in e["layers"])]


# ---------------------------------------------------------------------------------
# SketchUp Ruby: exact faces with holes, grouped and tagged per layer.
# ---------------------------------------------------------------------------------

def to_sketchup_rb(model, layers, name="RoomSketch") -> str:
    out = [
        f"# {name} - generated by RoomSketch {_dt.date.today().isoformat()}",
        "# SketchUp: Window > Ruby Console, then:  load '/path/to/this_file.rb'",
        "# (or Extensions > Developer > Ruby Console on newer versions)",
        "model = Sketchup.active_model",
        f"model.start_operation('{name}', true)",
        "root = model.active_entities.add_group",
        f"root.name = '{name}'",
        "def rs_pts(a) a.map { |p| Geom::Point3d.new(p[0].m, p[1].m, p[2].m) } end",
        "def rs_face(ents, outer, holes)",
        "  f = ents.add_face(rs_pts(outer)) rescue nil",
        "  return unless f",
        "  holes.each do |h|",
        "    hf = ents.add_face(rs_pts(h)) rescue nil",
        "    hf.erase! if hf && hf.valid?",
        "  end",
        "end",
    ]
    for layer in layers:
        faces = [f for f in model["faces"] if f["layer"] == layer]
        if not faces:
            continue
        out.append(f"tag = model.layers['{layer}'] || model.layers.add('{layer}')")
        out.append("g = root.entities.add_group")
        out.append(f"g.name = '{layer}'")
        out.append("g.layer = tag")
        for f in faces:
            out.append(f"rs_face(g.entities, {_rb(f['outer'])}, [{', '.join(_rb(h) for h in f['holes'])}])")
    out.append("model.commit_operation")
    out.append("model.active_view.zoom_extents")
    return "\n".join(out) + "\n"


def _rb(ring):
    return "[" + ",".join(f"[{p[0]:.4f},{p[1]:.4f},{p[2]:.4f}]" for p in ring) + "]"


# ---------------------------------------------------------------------------------
# Collada (.dae): imports in every SketchUp version. Triangles + edge lines.
# ---------------------------------------------------------------------------------

def to_dae(model, layers) -> str:
    geoms, nodes = [], []
    for layer in layers:
        faces = _faces(model, [layer])
        if not faces:
            continue
        V, T = [], []
        for f in faces:
            v, t = triangulate(f)
            T.extend((t + len(V)).tolist())
            V.extend(v.tolist())
        E = [e for e in _edges(model, layers) if next(l for l in e["layers"] if l in layers) == layer]
        LV = [p for e in E for p in (e["a"], e["b"])]
        gid = f"geom-{layer}"
        pos = " ".join(f"{x:.4f} {y:.4f} {z:.4f}" for x, y, z in V)
        lpos = " ".join(f"{x:.4f} {y:.4f} {z:.4f}" for x, y, z in LV)
        tris = " ".join(str(i) for tri in T for i in tri)
        lines = " ".join(str(i) for i in range(len(LV)))
        geoms.append(f"""
    <geometry id="{gid}" name="{layer}"><mesh>
      <source id="{gid}-pos"><float_array id="{gid}-pos-a" count="{len(V) * 3}">{pos}</float_array>
        <technique_common><accessor source="#{gid}-pos-a" count="{len(V)}" stride="3">
          <param name="X" type="float"/><param name="Y" type="float"/><param name="Z" type="float"/>
        </accessor></technique_common></source>
      <vertices id="{gid}-vtx"><input semantic="POSITION" source="#{gid}-pos"/></vertices>
      <triangles count="{len(T)}" material="mat"><input semantic="VERTEX" source="#{gid}-vtx" offset="0"/><p>{tris}</p></triangles>
    </mesh></geometry>""")
        if LV:
            geoms.append(f"""
    <geometry id="{gid}-edges" name="{layer}-edges"><mesh>
      <source id="{gid}-e-pos"><float_array id="{gid}-e-pos-a" count="{len(LV) * 3}">{lpos}</float_array>
        <technique_common><accessor source="#{gid}-e-pos-a" count="{len(LV)}" stride="3">
          <param name="X" type="float"/><param name="Y" type="float"/><param name="Z" type="float"/>
        </accessor></technique_common></source>
      <vertices id="{gid}-e-vtx"><input semantic="POSITION" source="#{gid}-e-pos"/></vertices>
      <lines count="{len(LV) // 2}" material="edge"><input semantic="VERTEX" source="#{gid}-e-vtx" offset="0"/><p>{lines}</p></lines>
    </mesh></geometry>""")
        inst = f"""<instance_geometry url="#{gid}"><bind_material><technique_common>
          <instance_material symbol="mat" target="#white"/></technique_common></bind_material></instance_geometry>"""
        if LV:
            inst += f"""<instance_geometry url="#{gid}-edges"><bind_material><technique_common>
          <instance_material symbol="edge" target="#black"/></technique_common></bind_material></instance_geometry>"""
        nodes.append(f'<node id="node-{layer}" name="{layer}">{inst}</node>')
    now = _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return f"""<?xml version="1.0" encoding="utf-8"?>
<COLLADA xmlns="http://www.collada.org/2005/11/COLLADASchema" version="1.4.1">
  <asset><contributor><authoring_tool>RoomSketch</authoring_tool></contributor>
    <created>{now}</created><modified>{now}</modified><unit name="meter" meter="1"/><up_axis>Z_UP</up_axis></asset>
  <library_effects>
    <effect id="white-fx"><profile_COMMON><technique sid="t"><lambert><diffuse><color>1 1 1 1</color></diffuse></lambert></technique></profile_COMMON></effect>
    <effect id="black-fx"><profile_COMMON><technique sid="t"><constant><emission><color>0 0 0 1</color></emission></constant></technique></profile_COMMON></effect>
  </library_effects>
  <library_materials>
    <material id="white" name="white"><instance_effect url="#white-fx"/></material>
    <material id="black" name="black"><instance_effect url="#black-fx"/></material>
  </library_materials>
  <library_geometries>{''.join(geoms)}
  </library_geometries>
  <library_visual_scenes><visual_scene id="scene">{''.join(nodes)}</visual_scene></library_visual_scenes>
  <scene><instance_visual_scene url="#scene"/></scene>
</COLLADA>
"""


# ---------------------------------------------------------------------------------
# DXF (R12 ASCII): 3DFACEs + LINE work on layers. SketchUp Pro / AutoCAD / Rhino.
# ---------------------------------------------------------------------------------

def to_dxf(model, layers, include_faces=True) -> str:
    o = ["0", "SECTION", "2", "HEADER", "9", "$ACADVER", "1", "AC1009", "9", "$INSUNITS", "70", "6",
         "0", "ENDSEC", "0", "SECTION", "2", "TABLES", "0", "TABLE", "2", "LAYER", "70", str(len(layers) * 2)]
    for l in layers:
        for name in (l.upper(), l.upper() + "_LINES"):
            o += ["0", "LAYER", "2", name, "70", "0", "62", "7", "6", "CONTINUOUS"]
    o += ["0", "ENDTAB", "0", "ENDSEC", "0", "SECTION", "2", "ENTITIES"]
    for e in _edges(model, layers):
        layer = next(l for l in e["layers"] if l in layers).upper() + "_LINES"
        a, b = e["a"], e["b"]
        o += ["0", "LINE", "8", layer, "10", f"{a[0]:.4f}", "20", f"{a[1]:.4f}", "30", f"{a[2]:.4f}",
              "11", f"{b[0]:.4f}", "21", f"{b[1]:.4f}", "31", f"{b[2]:.4f}"]
    if include_faces:
        for f in _faces(model, layers):
            v, t = triangulate(f)
            for tri in t:
                p = v[tri]
                o += ["0", "3DFACE", "8", f["layer"].upper(), "62", "7"]
                # 4th corner repeats the 3rd for a triangle; edges flagged invisible (70=15).
                for k, (x, y, z) in enumerate([p[0], p[1], p[2], p[2]]):
                    o += [str(10 + k), f"{x:.4f}", str(20 + k), f"{y:.4f}", str(30 + k), f"{z:.4f}"]
                o += ["70", "15"]
    o += ["0", "ENDSEC", "0", "EOF"]
    return "\n".join(o) + "\n"


# ---------------------------------------------------------------------------------
# OBJ: triangles grouped per layer + `l` edge elements.
# ---------------------------------------------------------------------------------

def to_obj(model, layers) -> str:
    o = ["# RoomSketch export, units: metres, Z up", "o RoomSketch"]
    base = 1
    for layer in layers:
        faces = _faces(model, [layer])
        if not faces:
            continue
        o.append(f"g {layer}")
        for f in faces:
            v, t = triangulate(f)
            o += [f"v {x:.4f} {y:.4f} {z:.4f}" for x, y, z in v]
            o += [f"f {a + base} {b + base} {c + base}" for a, b, c in t]
            base += len(v)
    o.append("g edges")
    for e in _edges(model, layers):
        o.append("v {:.4f} {:.4f} {:.4f}".format(*e["a"]))
        o.append("v {:.4f} {:.4f} {:.4f}".format(*e["b"]))
        o.append(f"l {base} {base + 1}")
        base += 2
    return "\n".join(o) + "\n"


# ---------------------------------------------------------------------------------
# SVG floor plan with dimensions.
# ---------------------------------------------------------------------------------

def to_svg_plan(room: dict, model: dict, scale: float = 1.0) -> str:
    s = scale
    P = np.array(room["polygon"], float) * s
    H = room["height"] * s
    px = 100.0  # px per metre
    pad = 1.2
    lo, hi = P.min(axis=0) - pad, P.max(axis=0) + pad
    W, Hh = (hi - lo) * px

    def tr(p):
        return ((p[0] - lo[0]) * px, (hi[1] - p[1]) * px)

    Q = np.array(model["outer_outline"])
    path = lambda ring: "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in map(tr, ring)) + " Z"
    g = [f'<path d="{path(Q)} {path(P[::-1])}" fill="#222" fill-rule="evenodd"/>']
    n = len(P)
    for op in room.get("openings", []):
        i = op["edge"]
        a, b = P[i], P[(i + 1) % n]
        d = (b - a) / np.linalg.norm(b - a)
        no = np.array([d[1], -d[0]])
        u0, u1 = op["u0"] * s, op["u1"] * s
        t = model["wall_thickness"]
        quad = [a + d * u0 - no * 0.01, a + d * u1 - no * 0.01, a + d * u1 + no * (t + 0.01), a + d * u0 + no * (t + 0.01)]
        g.append(f'<path d="{path(quad)}" fill="#fff" stroke="#222" stroke-width="1"/>')
        if op["kind"] == "window":
            m0, m1 = a + d * u0 + no * t / 2, a + d * u1 + no * t / 2
            g.append('<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" stroke="#222" stroke-width="1"/>' % (*tr(m0), *tr(m1)))
        else:
            w = u1 - u0
            hinge = a + d * u0
            tip = hinge - no * w
            end = a + d * u1
            x0, y0 = tr(hinge)
            x1, y1 = tr(tip)
            x2, y2 = tr(end)
            g.append(f'<line x1="{x0:.1f}" y1="{y0:.1f}" x2="{x1:.1f}" y2="{y1:.1f}" stroke="#222" stroke-width="1"/>')
            g.append(f'<path d="M{x1:.1f},{y1:.1f} A{w * px:.1f},{w * px:.1f} 0 0 1 {x2:.1f},{y2:.1f}" fill="none" stroke="#222" stroke-width="0.8" stroke-dasharray="4 3"/>')
    for f in room.get("furniture", []):
        c, sn = math.cos(f["yaw"]), math.sin(f["yaw"])
        ex, ey = np.array([c, sn]) * f["w"] * s / 2, np.array([-sn, c]) * f["d"] * s / 2
        ctr = np.array([f["cx"], f["cy"]]) * s
        g.append(f'<path d="{path([ctr - ex - ey, ctr + ex - ey, ctr + ex + ey, ctr - ex + ey])}" fill="none" stroke="#888" stroke-width="1"/>')
    # Dimension strings, offset outside each wall.
    for i in range(n):
        a, b = P[i], P[(i + 1) % n]
        L = np.linalg.norm(b - a)
        d = (b - a) / L
        no = np.array([d[1], -d[0]])
        off = 0.55
        a2, b2 = a + no * off, b + no * off
        (x1, y1), (x2, y2) = tr(a2), tr(b2)
        g.append(f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="#c33" stroke-width="0.8"/>')
        for p in (a, b):
            (ex1, ey1), (ex2, ey2) = tr(p + no * 0.2), tr(p + no * (off + 0.08))
            g.append(f'<line x1="{ex1:.1f}" y1="{ey1:.1f}" x2="{ex2:.1f}" y2="{ey2:.1f}" stroke="#c33" stroke-width="0.6"/>')
        mx, my = tr((a2 + b2) / 2 + no * 0.12)
        ang = math.degrees(math.atan2(-(b2 - a2)[1], (b2 - a2)[0]))
        if ang > 90 or ang < -90:
            ang += 180
        g.append(f'<text x="{mx:.1f}" y="{my:.1f}" font-size="14" text-anchor="middle" dominant-baseline="middle" '
                 f'fill="#c33" transform="rotate({ang:.1f} {mx:.1f} {my:.1f})">{_fmt_len(L)}</text>')
    from shapely.geometry import Polygon
    poly = Polygon(P)
    cx, cy = tr(np.array(poly.representative_point().coords[0]))
    g.append(f'<text x="{cx:.1f}" y="{cy:.1f}" font-size="16" text-anchor="middle" fill="#222">'
             f'{poly.area:.2f} m² · {poly.area * 10.7639:.0f} ft² · ceiling {_fmt_len(H)}</text>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W:.0f}" height="{Hh:.0f}" viewBox="0 0 {W:.0f} {Hh:.0f}" '
            f'font-family="Helvetica, Arial, sans-serif"><rect width="100%" height="100%" fill="#fff"/>'
            + "".join(g) + "</svg>\n")


def _fmt_len(m: float) -> str:
    inches = m / 0.0254
    ft = int(inches // 12)
    rem = inches - ft * 12
    if round(rem) == 12:
        ft, rem = ft + 1, 0
    return escape(f"{m:.2f} m ({ft}'-{round(rem)}\")")
